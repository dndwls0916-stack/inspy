function roleBlock(roleId) {
  const r = ROLES[roleId];
  if (!r) return '';
  return (
    `\n[역할] 이 회의에서 당신은 "${r.name}"입니다. 이 직업 전문가의 관점에서 발언하세요. 다른 참가자가 다른 관점으로 말하면 그 관점을 존중하되, 당신의 전문 영역에서 보완하거나 반박하세요.\n` +
    `관점: ${r.view}\n반드시 점검할 것:\n${r.checks.map((c) => `- ${c}`).join('\n')}\n주의: ${r.caution}\n`
  );
}

const roleName = (id) => ROLES[id]?.name || '';
const publicRoles = () =>
  Object.entries(ROLES)
    .map(([id, r]) => ({ id, name: r.name, icon: r.icon, group: r.group, view: r.view }))
    .sort((a, b) => GROUP_ORDER.indexOf(a.group) - GROUP_ORDER.indexOf(b.group)); // 같은 그룹 안에서는 정의 순서 유지(안정 정렬)

module.exports = { ROLES, TEAMS, roleBlock, roleName, publicRoles };
